// Managed model selection, shared by every provider. A Compose model request
// ("chat-default", a recipe key, or a provider-native model ID) is planned
// here into an ordered candidate list; each provider resolves that list
// against its own catalog (see ModelResolver) and persists the result in a
// ModelSelection resource so unchanged inputs never pick a different model.

// Model roles. Built-in aliases imply one; custom recipe keys declare one.
const (
	ModelRoleChat      = "chat"
	ModelRoleEmbedding = "embedding"
)

// Where a selection's candidates came from.
const (
	ModelSourceRecipe        = "recipe"         // a key in defang-<cloud>:models
	ModelSourceDefault       = "default"        // built-in alias missing from the recipe
	ModelSourceNative        = "native"         // a provider-native model ID
	ModelSourceLegacyPayload = "legacy-payload" // a gateway generated by an older CLI
)

// Recipe candidate fields. Keys are kebab-case like every other recipe key.
const (
	ModelFieldModel        = "model"
	ModelFieldVersion      = "version"
	ModelFieldRole         = "role"
	ModelFieldLocation     = "location"
	ModelFieldFormat       = "format"
	ModelFieldSku          = "sku"
	ModelFieldAllowPreview = "allow-preview"
)

const modelsRecipeKey = "models"

var (
	ErrModelRecipe        = errors.New("invalid model recipe")
	ErrModelRequest       = errors.New("invalid model request")
	ErrModelUnavailable   = errors.New("model unavailable")
	ErrModelAmbiguous     = errors.New("ambiguous model request")
	ErrEmbeddingMigration = errors.New("embedding model change requires an explicit migration")
)

// builtinModelRoles are the Defang model aliases every cloud supports.
var builtinModelRoles = map[string]string{
	"chat-default":      ModelRoleChat,
	"chat-large":        ModelRoleChat,
	"embedding-default": ModelRoleEmbedding,
}

// ModelCloud describes one provider's recipe rules and compatibility defaults.
type ModelCloud struct {
	// Name is the cloud name used in messages, e.g. "aws".
	Name string
	// Namespace is the recipe config namespace, e.g. "defang-aws".
	Namespace string
	// Fields are the optional candidate fields this cloud accepts besides model and role.
	Fields []string
	// Defaults are the compatibility candidates for built-in aliases a recipe omits.
	Defaults map[string][]compose.ModelCandidate
	// NativeExact reports whether a request is syntactically an exact model
	// reference that bypasses recipe keys (AWS revisions and ARNs). Nil when
	// the cloud has no such syntax.
	NativeExact func(model string) bool
	// CandidateExact reports whether a candidate names one concrete model
	// revision, i.e. needs no catalog lookup to pick a revision.
	CandidateExact func(c compose.ModelCandidate) bool
	// RoleFromCatalog is true when the resolver can establish a model's role
	// from verified catalog metadata, so custom keys may omit it.
	RoleFromCatalog bool
}

func (mc ModelCloud) allows(field string) bool {
	return field == ModelFieldModel || field == ModelFieldRole || slices.Contains(mc.Fields, field)
}

// IsExact reports whether every candidate names one concrete revision.
func (mc ModelCloud) IsExact(candidates []compose.ModelCandidate) bool {
	if len(candidates) != 1 {
		return false
	}
	if mc.CandidateExact == nil {
		return true
	}
	return mc.CandidateExact(candidates[0])
}

// ModelRecipe maps a selector to its ordered candidates.
type ModelRecipe map[string][]compose.ModelCandidate

// ReadModelRecipe reads and validates defang-<cloud>:models from stack config.
// An absent key is an empty recipe; a malformed one is an error.
func ReadModelRecipe(ctx *pulumi.Context, mc ModelCloud) (ModelRecipe, error) {
	raw, err := config.New(ctx, mc.Namespace).Try(modelsRecipeKey)
	if err != nil || raw == "" {
		return ModelRecipe{}, nil //nolint:nilerr // absent config is an empty recipe
	}
	return ParseModelRecipe(mc, raw)
}

// ParseModelRecipe validates the JSON form of a defang-<cloud>:models value.
func ParseModelRecipe(mc ModelCloud, raw string) (ModelRecipe, error) {
	key := mc.Namespace + ":" + modelsRecipeKey
	var root any
	if err := json.Unmarshal([]byte(raw), &root); err != nil {
		return nil, fmt.Errorf("%w: %s is not valid JSON/YAML structured config: %w", ErrModelRecipe, key, err)
	}
	selectors, ok := root.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("%w: %s must map each selector to a list of candidates, e.g. "+
			"`chat-default: [{model: <id>}]`", ErrModelRecipe, key)
	}
	recipe := make(ModelRecipe, len(selectors))
	for selector, value := range Sorted(selectors) {
		candidates, err := parseCandidates(mc, key, selector, value)
		if err != nil {
			return nil, err
		}
		recipe[selector] = candidates
	}
	return recipe, nil
}

func parseCandidates(mc ModelCloud, key, selector string, value any) ([]compose.ModelCandidate, error) {
	where := fmt.Sprintf("%s.%s", key, selector)
	list, ok := value.([]any)
	if !ok || len(list) == 0 {
		return nil, fmt.Errorf("%w: %s must be a non-empty list of candidates, e.g. `%s: [{model: <id>}]`",
			ErrModelRecipe, where, selector)
	}
	candidates := make([]compose.ModelCandidate, 0, len(list))
	for i, item := range list {
		at := fmt.Sprintf("%s[%d]", where, i)
		obj, ok := item.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("%w: %s must be an object with at least `model`", ErrModelRecipe, at)
		}
		var c compose.ModelCandidate
		for field, v := range Sorted(obj) {
			if !mc.allows(field) {
				return nil, fmt.Errorf("%w: %s: field %q is not supported on %s (supported: %s)",
					ErrModelRecipe, at, field, mc.Name, strings.Join(mc.supportedFields(), ", "))
			}
			if field == ModelFieldAllowPreview {
				b, ok := v.(bool)
				if !ok {
					return nil, fmt.Errorf("%w: %s: %q must be true or false", ErrModelRecipe, at, field)
				}
				c.AllowPreview = b
				continue
			}
			str, ok := scalarString(v)
			if !ok {
				return nil, fmt.Errorf("%w: %s: %q must be a string", ErrModelRecipe, at, field)
			}
			switch field {
			case ModelFieldModel:
				c.Model = str
			case ModelFieldVersion:
				c.Version = str
			case ModelFieldRole:
				c.Role = str
			case ModelFieldLocation:
				c.Location = str
			case ModelFieldFormat:
				c.Format = str
			case ModelFieldSku:
				c.Sku = str
			}
		}
		if strings.TrimSpace(c.Model) == "" {
			return nil, fmt.Errorf("%w: %s: `model` is required, e.g. `{model: <provider model id>}`", ErrModelRecipe, at)
		}
		if strings.Contains(c.Model, "${") {
			return nil, fmt.Errorf("%w: %s: model %q contains an unresolved interpolation", ErrModelRecipe, at, c.Model)
		}
		if c.Role != "" && c.Role != ModelRoleChat && c.Role != ModelRoleEmbedding {
			return nil, fmt.Errorf("%w: %s: role %q must be %q or %q", ErrModelRecipe, at, c.Role,
				ModelRoleChat, ModelRoleEmbedding)
		}
		if builtin, ok := builtinModelRoles[selector]; ok && c.Role != "" && c.Role != builtin {
			return nil, fmt.Errorf("%w: %s: %s is reserved for %s models; remove role %q", ErrModelRecipe, at,
				selector, builtin, c.Role)
		}
		candidates = append(candidates, c)
	}
	for i := 1; i < len(candidates); i++ {
		if candidates[i].Role != candidates[0].Role {
			return nil, fmt.Errorf("%w: %s: all candidates of one selector must share a role (%q vs %q)",
				ErrModelRecipe, where, candidates[0].Role, candidates[i].Role)
		}
	}
	return candidates, nil
}

func (mc ModelCloud) supportedFields() []string {
	return append([]string{ModelFieldModel, ModelFieldRole}, mc.Fields...)
}

// scalarString accepts strings and numbers: a YAML `version: 1` arrives as a
// number but means the revision "1".
func scalarString(v any) (string, bool) {
	switch t := v.(type) {
	case string:
		return t, true
	case float64:
		return strconv.FormatFloat(t, 'f', -1, 64), true
	default:
		return "", false
	}
}

// NormalizeModelRequest maps the Docker-style "ai/" spellings of the built-in
// aliases to the bare alias. Other names are returned unchanged.
func NormalizeModelRequest(request string) string {
	request = strings.TrimSpace(request)
	if alias, ok := strings.CutPrefix(request, "ai/"); ok {
		if _, builtin := builtinModelRoles[alias]; builtin {
			return alias
		}
	}
	return request
}

// ModelPlan is a planned model request: what to resolve and how.
type ModelPlan struct {
	// Request is the normalized request; on gateway clouds it is also the
	// application-facing model name.
	Request string
	// Role is the request's role, or "" when it is established at resolution.
	Role string
	// Candidates are tried in order.
	Candidates []compose.ModelCandidate
	// Source says where the candidates came from.
	Source string
}

// PlanModelRequest applies the precedence rules: native exact references,
// then recipe keys, then compatibility defaults for built-in aliases, then the
// request as a provider-native model.
func PlanModelRequest(mc ModelCloud, request string, recipe ModelRecipe) (ModelPlan, error) {
	req := NormalizeModelRequest(request)
	if req == "" {
		return ModelPlan{}, fmt.Errorf("%w: empty model name", ErrModelRequest)
	}
	if strings.Contains(req, "${") {
		return ModelPlan{}, fmt.Errorf("%w: model %q contains an unresolved interpolation; set the model name "+
			"literally or define a recipe key", ErrModelRequest, req)
	}
	builtinRole, builtin := builtinModelRoles[req]
	plan := ModelPlan{Request: req, Role: builtinRole}

	switch candidates, inRecipe := recipe[req]; {
	case mc.NativeExact != nil && mc.NativeExact(req):
		plan.Source = ModelSourceNative
		plan.Candidates = []compose.ModelCandidate{{Model: req}}
	case inRecipe:
		plan.Source = ModelSourceRecipe
		plan.Candidates = candidates
		if !builtin {
			plan.Role = candidates[0].Role
			if plan.Role == "" && !mc.RoleFromCatalog {
				return ModelPlan{}, fmt.Errorf("%w: %s:%s.%s needs `role: chat` or `role: embedding`; %s has no "+
					"catalog metadata to establish it", ErrModelRecipe, mc.Namespace, modelsRecipeKey, req, mc.Name)
			}
		}
	case builtin:
		plan.Source = ModelSourceDefault
		plan.Candidates = mc.Defaults[req]
		if len(plan.Candidates) == 0 {
			return ModelPlan{}, fmt.Errorf("%w: %s has no default for %q; add %s:%s.%s to the recipe",
				ErrModelRequest, mc.Name, req, mc.Namespace, modelsRecipeKey, req)
		}
	default:
		plan.Source = ModelSourceNative
		plan.Candidates = []compose.ModelCandidate{{Model: req}}
	}
	return plan, nil
}

// CompareRevisions orders model revisions the way providers number them:
// runs of digits compare numerically ("10" > "9", "2025-04-14" >
// "2024-11-20"), everything else lexically. It is not SemVer.
func CompareRevisions(a, b string) int {
	for a != "" && b != "" {
		ca, ra := revisionChunk(a)
		cb, rb := revisionChunk(b)
		if c := compareChunk(ca, cb); c != 0 {
			return c
		}
		a, b = ra, rb
	}
	switch {
	case a == "" && b == "":
		return 0
	case a == "":
		return -1
	default:
		return 1
	}
}

func revisionChunk(s string) (string, string) {
	digit := isDigit(s[0])
	i := 1
	for i < len(s) && isDigit(s[i]) == digit {
		i++
	}
	return s[:i], s[i:]
}

func compareChunk(a, b string) int {
	if isDigit(a[0]) && isDigit(b[0]) {
		a, b = strings.TrimLeft(a, "0"), strings.TrimLeft(b, "0")
		if len(a) != len(b) {
			return len(a) - len(b)
		}
	}
	return strings.Compare(a, b)
}

func isDigit(c byte) bool { return c >= '0' && c <= '9' }

// Gateway support: on AWS and GCP a managed model is served by a LiteLLM
// container whose single model is the resolved target.

const liteLLMRepo = "litellm/litellm"

// GatewayCommand is the LiteLLM command serving target under appName, the
// name the CLI gave applications.
// LiteLLM's single-model CLI mode routes every chat and embedding request to
// --model whatever model name the request carries, so names an application
// was given by an earlier deployment keep working.
func GatewayCommand(liteLLMProvider, target, appName string) []string {
	if !strings.HasPrefix(target, liteLLMProvider+"/") {
		target = liteLLMProvider + "/" + target
	}
	return []string{"--drop_params", "--model", target, "--alias", appName}
}

// LegacyGateway recognizes a gateway generated by a CLI that resolved models
// itself: image litellm/litellm:<tag> and exactly
// `--drop_params --model <target> --alias <alias>`. Returns the target
// (without its LiteLLM provider prefix) and the alias. User-managed LiteLLM
// services do not match and are never rewritten.
func LegacyGateway(svc compose.ServiceConfig, liteLLMProvider string) (string, string, bool) {
	img := svc.StaticImage()
	if img == nil {
		return "", "", false
	}
	repo, _, _ := strings.Cut(strings.TrimPrefix(*img, "docker.io/"), ":")
	if repo != liteLLMRepo {
		return "", "", false
	}
	c := svc.Command
	if len(c) != 5 || c[0] != "--drop_params" || c[1] != "--model" || c[3] != "--alias" || c[2] == "" || c[4] == "" {
		return "", "", false
	}
	return strings.TrimPrefix(c[2], liteLLMProvider+"/"), c[4], true
}

// IsManagedGateway reports whether a service is a CLI-generated model gateway
// the provider configures: marked x-defang-llm, named after a top-level
// Compose model, and without a command. A gateway with a command was resolved
// by an older CLI (see LegacyGateway); one that is not named after a model is
// user-managed.
func IsManagedGateway(name string, svc compose.ServiceConfig, models compose.Models) bool {
	_, isModel := models[name]
	return svc.LLM != nil && len(svc.Command) == 0 && isModel
}

// InjectModelVar writes value into the model variable of every service bound
// to model (`services.<svc>.models.<model>`) unless the service already sets
// it, which means the user chose the value. Services without the binding are
// never touched.
func InjectModelVar(services compose.Services, model string, value pulumi.StringInput) error {
	for name, svc := range Sorted(services) {
		binding, ok := svc.Models[model]
		if !ok {
			continue
		}
		if binding == nil || binding.ModelVar == "" {
			return fmt.Errorf("%w: service %q binds model %q without model_var", ErrModelRequest, name, model)
		}
		if _, set := svc.Environment[binding.ModelVar]; set {
			continue
		}
		env := make(compose.Environment, len(svc.Environment)+1)
		for k, v := range svc.Environment {
			env[k] = v
		}
		env[binding.ModelVar] = value
		svc.Environment = env
		services[name] = svc
	}
	return nil
}

// GatewayModels prepares managed model services served by a LiteLLM gateway
// container (AWS, GCP): it records each selection and generates the gateway
// command and routing environment from it.
type GatewayModels struct {
	Cloud ModelCloud
	// Package is the provider package, e.g. "defang-aws".
	Package string
	// LiteLLMProvider is the LiteLLM provider prefix, e.g. "bedrock".
	LiteLLMProvider string
	// Region is the deployment region.
	Region   string
	PluginID PluginIdentity
	// Env sets the gateway's routing variables from its selection.
	Env func(env compose.Environment, sel *ModelSelectionResult)
	// LegacyLocationEnv names the gateway variable an older CLI used for the
	// model location, recorded with a legacy selection ("" if none).
	LegacyLocationEnv string
}

// Prepare returns services with every managed model gateway configured.
// Legacy CLI-generated gateways are deployed unchanged but recorded, so a
// later deployment knows what they served. User-managed LLM services are
// left alone. Consumers are never touched: the CLI wrote the
// application-facing name, which the gateway serves.
func (g GatewayModels) Prepare(
	ctx *pulumi.Context, services compose.Services, models compose.Models, opts ...pulumi.ResourceOption,
) (compose.Services, error) {
	if !IsProjectUsingLLM(services) {
		return services, nil
	}
	recipe, err := ReadModelRecipe(ctx, g.Cloud)
	if err != nil {
		return nil, err
	}
	out := make(compose.Services, len(services))
	for name, svc := range services {
		out[name] = svc
	}
	for name, svc := range Sorted(services) {
		switch {
		case IsManagedGateway(name, svc, models):
			model := models[name]
			plan, err := PlanModelRequest(g.Cloud, model.Model, recipe)
			if err != nil {
				return nil, fmt.Errorf("model %q: %w", name, err)
			}
			sel, err := RegisterModelSelection(ctx, g.Package, name, plan, g.Region, nil, model.Seed, g.PluginID, opts...)
			if err != nil {
				return nil, err
			}
			appName := plan.Request
			svc.GeneratedCommand = sel.Model.ApplyT(func(model string) []string {
				return GatewayCommand(g.LiteLLMProvider, model, appName)
			}).(pulumi.StringArrayOutput)
			env := make(compose.Environment, len(svc.Environment)+2)
			for k, v := range svc.Environment {
				env[k] = v
			}
			g.Env(env, sel)
			svc.Environment = env
			out[name] = svc
		case svc.LLM != nil:
			target, alias, ok := LegacyGateway(svc, g.LiteLLMProvider)
			if !ok {
				continue // user-managed: only the cloud permissions apply
			}
			candidate := compose.ModelCandidate{Model: target}
			if g.LegacyLocationEnv != "" {
				if loc, _ := compose.StaticEnvValue(svc.Environment[g.LegacyLocationEnv]); loc != nil {
					candidate.Location = *loc
				}
			}
			plan := ModelPlan{
				Request:    NormalizeModelRequest(alias),
				Role:       builtinModelRoles[NormalizeModelRequest(alias)],
				Candidates: []compose.ModelCandidate{candidate},
				Source:     ModelSourceLegacyPayload,
			}
			_, err := RegisterModelSelection(ctx, g.Package, name, plan, g.Region, nil, nil, g.PluginID, opts...)
			if err != nil {
				return nil, err
			}
		}
	}
	return out, nil
}

// SetEnvDefault sets key unless the service already sets it.
func SetEnvDefault(env compose.Environment, key string, value pulumi.StringInput) {
	if _, ok := env[key]; !ok {
		env[key] = value
	}
}
